STYLES["taxi"] = {**STYLES["sedan"], "sign": True}

SCALE = 2.2  # unités jouet -> mètres (config.CAR_SCALE)
WHEEL_R0 = 0.145


class Dims:
    """Dimensions d'un gabarit en mètres (repère : essieu arrière)."""

    def __init__(self, style):
        s = STYLES[style]
        wy, track = s["wheels"]
        keys = s["keys"]
        self.style = style
        self.axle_y = wy * SCALE  # origine du modèle -> essieu arrière
        self.wb = 2 * wy * SCALE  # empattement
        self.nose = (wy - keys[0][0]) * SCALE  # essieu arrière -> nez
        self.tail = (keys[-1][0] - wy) * SCALE  # essieu arrière -> arrière
        self.half_w = max(k[4] for k in keys) * SCALE
        self.track = track * SCALE
        self.wheel_scale = s.get("wheel_scale", 1.0)
        self.wheel_r = WHEEL_R0 * self.wheel_scale * SCALE
        self.height = (max(k[2] for k in keys) + (0.09 if s.get("sign") else 0.0)) * SCALE
        self.length = self.nose + self.tail


_DIMS = {}


def dims(style):
    if style not in _DIMS:
        _DIMS[style] = Dims(style)
    return _DIMS[style]
